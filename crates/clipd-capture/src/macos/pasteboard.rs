//! NSPasteboard reads and writes.
//!
//! The pasteboard is item-based: every copy is a list of
//! `NSPasteboardItem`s, each carrying several UTIs. Reading follows the
//! same priority as the other backends: file URLs, text (+ HTML), image.

use anyhow::{Context, Result, bail};
use clipd_core::{RawClip, RawContent};
use objc2::rc::{Retained, autoreleasepool};
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardItem, NSPasteboardTypeFileURL, NSPasteboardTypeHTML,
    NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF,
};
use objc2_foundation::{NSArray, NSData, NSString, NSURL};

use crate::WriteContent;

// Extern-static UTIs (unsafe to touch: they are linked addresses).
fn t_file_url() -> &'static NSString {
    unsafe { NSPasteboardTypeFileURL }
}
fn t_string() -> &'static NSString {
    unsafe { NSPasteboardTypeString }
}
fn t_html() -> &'static NSString {
    unsafe { NSPasteboardTypeHTML }
}
fn t_png() -> &'static NSString {
    unsafe { NSPasteboardTypePNG }
}
fn t_tiff() -> &'static NSString {
    unsafe { NSPasteboardTypeTIFF }
}

/// UTIs producers use to say "don't record this" (1Password, Maccy-aware
/// apps, KeePassXC, transient/auto-generated content).
const EXCLUDE_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.pheab.clipboardmanager.ignore",
    "Pasteboard generator type",
];

/// UTI list the change is advertised under (`pb.types()` covers all items).
fn offered_types(pb: &NSPasteboard) -> Vec<String> {
    pb.types()
        .map(|types| types.iter().map(|t| t.to_string()).collect())
        .unwrap_or_default()
}

fn is_excluded(offered: &[String]) -> bool {
    offered
        .iter()
        .any(|o| EXCLUDE_TYPES.iter().any(|e| o.eq_ignore_ascii_case(e)))
}

fn url_to_path(s: &NSString) -> Option<String> {
    NSURL::URLWithString(s).and_then(|u| u.path().map(|p| p.to_string()))
}

/// Read the current pasteboard content, or None when empty/unsupported or
/// the producer opted out. Body content is never logged.
pub(super) fn read_content() -> Option<RawContent> {
    autoreleasepool(|_| {
        let pb = NSPasteboard::generalPasteboard();
        let offered = offered_types(&pb);
        if is_excluded(&offered) {
            tracing::debug!("pasteboard change excluded by producer opt-out UTI");
            return None;
        }

        // Files: one item per copied file, each carrying public.file-url.
        let mut files: Vec<String> = Vec::new();
        if let Some(items) = pb.pasteboardItems() {
            for item in items.iter() {
                if item.types().iter().any(|t| *t == *t_file_url())
                    && let Some(s) = item.stringForType(t_file_url())
                    && let Some(path) = url_to_path(&s)
                {
                    files.push(path);
                }
            }
        }
        if !files.is_empty() {
            tracing::debug!(count = files.len(), "pasteboard files");
            return Some(RawContent::Files(files));
        }

        if let Some(text) = pb.stringForType(t_string()).filter(|t| !t.is_empty()) {
            let html = pb
                .stringForType(t_html())
                .map(|h| h.to_string())
                .or_else(|| {
                    pb.dataForType(t_html())
                        .map(|d| String::from_utf8_lossy(&d.to_vec()).into_owned())
                });
            tracing::debug!(chars = text.length(), "pasteboard text");
            return Some(RawContent::Text {
                text: text.to_string(),
                html,
            });
        }

        for t in [t_png(), t_tiff()] {
            if let Some(data) = pb.dataForType(t) {
                match image::load_from_memory(&data.to_vec()) {
                    Ok(img) => {
                        let rgba = img.to_rgba8();
                        let (w, h) = rgba.dimensions();
                        tracing::debug!(width = w, height = h, "pasteboard image");
                        return Some(RawContent::Image {
                            width: w,
                            height: h,
                            rgba: rgba.into_raw(),
                        });
                    }
                    Err(e) => {
                        tracing::debug!(error = %e, "pasteboard image undecodable")
                    }
                }
            }
        }
        None
    })
}

pub(super) fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_millis() as i64)
}

pub fn read_current() -> Result<Option<RawClip>> {
    Ok(read_content().map(|content| RawClip {
        content,
        source_app: super::paste::source_app_now(),
        captured_at: now_ms(),
    }))
}

/// Write one item carrying `entries` (UTI -> payload) — used by tests for
/// opt-out types as well as by `write_clip`.
pub(super) fn write_item(entries: &[(&NSString, ItemData)]) -> bool {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    let item = NSPasteboardItem::new();
    for (ty, data) in entries {
        match data {
            ItemData::Text(s) => {
                item.setString_forType(&NSString::from_str(s), ty);
            }
            ItemData::Bytes(b) => {
                item.setData_forType(&NSData::from_vec(b.clone()), ty);
            }
        }
    }
    // NSPasteboardItem conforms to NSPasteboardWriting; writeObjects both
    // declares the item's types and delivers its data.
    pb.writeObjects(&NSArray::from_retained_slice(&[
        ProtocolObject::from_retained(item),
    ]))
}

pub(super) enum ItemData {
    Text(String),
    Bytes(Vec<u8>),
}

fn text_offers(text: &str, html: Option<&str>) -> Vec<(&'static NSString, ItemData)> {
    // 'static: the UTI statics outlive the call; write_item accepts &NSString.
    let mut v = vec![(t_string(), ItemData::Text(text.to_owned()))];
    if let Some(h) = html {
        v.push((t_html(), ItemData::Text(h.to_owned())));
    }
    v
}

/// Write the stored clip back. Files go on as one item per file URL so
/// Finder and file inputs accept them.
pub fn write_clip(content: WriteContent<'_>) -> Result<()> {
    autoreleasepool(|_| -> Result<()> {
        match content {
            WriteContent::Text { text, html } => {
                if !write_item(&text_offers(text, html)) {
                    bail!("NSPasteboard refused the text write");
                }
            }
            WriteContent::ImagePng(path) => {
                let png = std::fs::read(path).with_context(|| format!("reading {path}"))?;
                image::load_from_memory_with_format(&png, image::ImageFormat::Png)
                    .with_context(|| format!("decoding PNG {path}"))?;
                if !write_item(&[(t_png(), ItemData::Bytes(png))]) {
                    bail!("NSPasteboard refused the image write");
                }
            }
            WriteContent::Files(files) => {
                let pb = NSPasteboard::generalPasteboard();
                pb.clearContents();
                let urls: Vec<Retained<ProtocolObject<dyn objc2_app_kit::NSPasteboardWriting>>> =
                    files
                        .iter()
                        .map(|f| {
                            ProtocolObject::from_retained(NSURL::fileURLWithPath(
                                &NSString::from_str(f),
                            ))
                        })
                        .collect();
                if urls.is_empty() {
                    bail!("no file paths to put on the clipboard");
                }
                if !pb.writeObjects(&NSArray::from_retained_slice(&urls)) {
                    bail!("NSPasteboard refused the file list");
                }
            }
        }
        Ok(())
    })
}
